import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {DatabaseSync} from 'node:sqlite';
import {startBridge} from './rust-bridge-client.mjs';

const executable = path.resolve(process.argv[2] || `ReverieCli-rs/target/release/reverie${process.platform === 'win32'?'.exe':''}`);
const directory = path.resolve(process.argv[3] || '.runtime/rust-3.0/session-smoke');
fs.mkdirSync(directory, {recursive:true});
const root = fs.mkdtempSync(path.join(directory, 'case-'));
const appRoot = path.join(root,'application');
const project = path.join(root,'工作区😀');
fs.mkdirSync(project,{recursive:true});
fs.mkdirSync(path.join(appRoot,'.reverie/Providers'),{recursive:true});
const configPath = path.join(appRoot,'.reverie/config.json');
const initial = {mode:'reverie', active_model_source:'standard',active_model_index:0,stream_responses:true,auto_index:true,max_context_tokens:128000,
  provider_files:{standard:'Manual Models.json'},private_extension:{preserve:['中文','😀']}};
fs.writeFileSync(configPath,JSON.stringify(initial));
fs.writeFileSync(path.join(appRoot,'.reverie/Providers/Manual Models.json'),JSON.stringify({provider_id:'standard',models:[{model:'local-model',profile_id:'profile-one',provider:'openai-chat',base_url:'http://127.0.0.1:1/v1',api_key:'FIXTURE_SECRET'}]}));
const originalConfig = fs.readFileSync(configPath);
let bridge = startBridge(executable,project,appRoot);
const checks = [];
async function request(action,payload,kind) {
  const reply=await bridge.request(action,payload);
  if(kind) assert.equal(reply.type,kind,JSON.stringify(reply));
  checks.push({action,type:reply.type});
  return reply;
}
try {
  await bridge.ready;
  const state=await request('initialize',{projectRoot:project},'state');
  assert.equal(state.state.models.active_model.id,'local-model');
  assert(!JSON.stringify(state).includes('FIXTURE_SECRET'));
  const first=(await request('createSession',{name:'第一段😀'},'session.created')).session;
  const second=(await request('createSession',{name:'second'},'session.created')).session;
  await request('setSetting',{sessionId:first.id,key:'mode',value:'writer'},'setting.updated');
  assert.equal((await request('getConversationConfig',{sessionId:first.id},'conversation.config')).configuration.settings.mode,'writer');
  assert.equal((await request('getConversationConfig',{sessionId:second.id},'conversation.config')).configuration.settings.mode,'reverie');
  await request('getSession',{sessionId:first.id,select:false},'session');
  assert.equal((await request('listSessions',{},'sessions')).sessions.current_session_id,second.id);
  const snapshot=await request('getConversationConfig',{sessionId:first.id},'conversation.config');
  await request('archiveSession',{sessionId:first.id,revision:snapshot.revision,archived:true},'sessions');
  await request('archiveSession',{sessionId:first.id,revision:snapshot.revision,archived:false},'error');
  await request('setSetting',{key:'stream_responses',value:false},'setting.updated');
  assert.deepEqual(JSON.parse(fs.readFileSync(configPath,'utf8')).private_extension,initial.private_extension);
  const backups=fs.readdirSync(path.join(appRoot,'.reverie/backups'));
  assert(backups.some(name=>fs.readFileSync(path.join(appRoot,'.reverie/backups',name)).equals(originalConfig)));
  await request('deleteSession',{sessionId:first.id},'error');
  const dataRoot=state.state.workspace.project_data_dir;
  await request('shutdown',{},'shutdown');
  assert.equal((await bridge.closed).code,0);
  const dbPath=path.join(dataRoot,'conversations.sqlite3');
  const db=new DatabaseSync(path.toNamespacedPath(dbPath));
  const messages=Array.from({length:73},(_,i)=>JSON.stringify({role:'Reverie',content:`${i}\r\n正文😀\n`,unknown:{keep:true}}));
  const insert=db.prepare('INSERT INTO messages VALUES (?,?,?,?,?)');
  db.exec('BEGIN IMMEDIATE');
  for(let i=0;i<messages.length;i++) insert.run(second.id,i,`fixture-${i}`,messages[i],crypto.createHash('sha256').update(messages[i]).digest('hex'));
  db.prepare('UPDATE conversations SET message_count=73,revision=revision+1 WHERE id=?').run(second.id);
  db.exec('COMMIT');
  const rawBefore=db.prepare('SELECT payload FROM messages ORDER BY sequence').all().map(row=>row.payload);
  db.close();
  bridge=startBridge(executable,project,appRoot);
  await bridge.ready;
  const tail=(await request('getSession',{sessionId:second.id,select:false,limit:60},'session')).session;
  assert.equal(tail.total,73);assert.equal(tail.before,13);assert.equal(tail.messages[0].content,'13\r\n正文😀\n');assert.equal(tail.messages[0].role,'assistant');
  const head=(await request('getSession',{sessionId:second.id,select:false,before:tail.before},'session')).session;
  assert.equal(head.messages.length,13);assert.equal(head.before,null);
  await request('renameSession',{sessionId:second.id,name:'renamed'},'session.updated');
  const read=new DatabaseSync(path.toNamespacedPath(dbPath),{readOnly:true});
  assert.deepEqual(read.prepare('SELECT payload FROM messages ORDER BY sequence').all().map(row=>row.payload),rawBefore);
  read.close();
  await request('deleteSession',{sessionId:first.id,confirmed:true},'session.updated');
  await request('getSession',{sessionId:first.id},'error');
  await request('shutdown',{},'shutdown');
  assert.equal((await bridge.closed).code,0);
  const backup=path.join(dataRoot,'backups/conversations.before-rust-3.0.sqlite3');
  const backupDb=new DatabaseSync(path.toNamespacedPath(backup),{readOnly:true});
  assert.equal(backupDb.prepare('PRAGMA quick_check').get().quick_check,'ok');
  assert.equal(backupDb.prepare('SELECT count(*) AS count FROM messages').get().count,73);
  backupDb.close();
  const report={schema:'reverie.rust-session-smoke.v1',passed:true,verified_at:new Date().toISOString(),executable,executable_sha256:crypto.createHash('sha256').update(fs.readFileSync(executable)).digest('hex'),root,checks,scope:'Actual JSONL, provider-file read, configuration backup, session isolation, revision conflict, paging, raw transcript bytes and restart; not complete legacy data acceptance.'};
  fs.writeFileSync(path.join(root,'report.json'),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify({passed:true,checks:checks.length,report:path.join(root,'report.json')}));
}finally { if(bridge.child.exitCode===null) {bridge.child.stdin.end();await bridge.closed;} }
