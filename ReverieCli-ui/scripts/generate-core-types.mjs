import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const uiRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(uiRoot, 'src/generated/core-types.ts');
const metadata = spawnSync('cargo', ['metadata', '--manifest-path', path.join(uiRoot, '../ReverieCli-rs/Cargo.toml'), '--no-deps', '--format-version', '1', '--locked'], {encoding: 'utf8', windowsHide: true, cwd: path.resolve(uiRoot, '..')});
if (metadata.status !== 0) throw new Error(`Could not resolve the Rust build directory: ${metadata.error?.message || metadata.stderr}`);
const executable = path.join(JSON.parse(metadata.stdout).target_directory, 'release', process.platform === 'win32' ? 'reverie.exe' : 'reverie');
const result = spawnSync(executable, ['--protocol-types'], {encoding: 'utf8', windowsHide: true});
if (result.status !== 0 || !result.stdout.startsWith('// Generated by the Rust protocol crate.')) {
  throw new Error(`Build the Rust release program before generating types: ${result.error?.message || result.stderr}`);
}
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replace(/\r\n/g,'\n') !== result.stdout.replace(/\r\n/g,'\n')) throw new Error('Rust protocol types have changed. Run npm run generate:core-types.');
} else {
  mkdirSync(path.dirname(target), {recursive: true});
  writeFileSync(target, result.stdout, 'utf8');
}
console.log(`Rust protocol types ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${target}`);
